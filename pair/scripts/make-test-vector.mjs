// Seals a payload exactly as the pairing page does and writes everything the watch needs to open it
// as a JSON test vector (core/src/test/resources/pairing-vector.json). The Kotlin test then proves
// that the watch opens the page's ciphertext and computes the same verification code.
//
//   node scripts/make-test-vector.mjs <output.json>
//
// Runs the page's own crypto.ts (Node strips the TypeScript types itself).

import { writeFileSync } from "node:fs";
import { base64UrlEncode, seal, suite, PAIRING_VERSION } from "../src/page/crypto.ts";

const out = process.argv[2];
if (!out) throw new Error("usage: make-test-vector.mjs <output.json>");

const keyPair = await suite.kem.generateKeyPair();
const publicKey = new Uint8Array(await suite.kem.serializePublicKey(keyPair.publicKey));
const privateKey = new Uint8Array(await suite.kem.serializePrivateKey(keyPair.privateKey));
const pairingId = base64UrlEncode(crypto.getRandomValues(new Uint8Array(16)));
const payload = { v: PAIRING_VERSION, provider: "gemini", apiKey: "AIzaSyTestVector-not-a-real-key-0123456789" };

const { sealed, code } = await seal(publicKey, pairingId, payload);

writeFileSync(
  out,
  JSON.stringify(
    {
      note: "Generated by pair/scripts/make-test-vector.mjs. Test data only.",
      privateKey: base64UrlEncode(privateKey),
      publicKey: base64UrlEncode(publicKey),
      pairingId,
      provider: payload.provider,
      apiKey: payload.apiKey,
      sealed: base64UrlEncode(sealed),
      code,
    },
    null,
    2,
  ) + "\n",
);
console.log(`wrote ${out} (code ${code})`);
